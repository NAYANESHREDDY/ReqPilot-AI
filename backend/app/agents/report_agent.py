from datetime import datetime
from typing import List, Dict, Any


class ReportGenerationAgent:
    """
    Deterministic engineering report generator.

    Generates six reports from persisted project artifacts:
      1. Software Requirements Specification
      2. Requirements Quality & Risk Audit
      3. System Architecture Proposal
      4. Project Plan & Sprint Schedule
      5. Traceability Matrix
      6. Requirements Change Impact Report

    The agent does not invent project-specific evidence.
    Missing values are represented explicitly instead of being replaced
    with fabricated IDs, pages, scores, technologies, or approval states.
    """

    # ------------------------------------------------------------------
    # Helpers
    # ------------------------------------------------------------------

    @staticmethod
    def _display(value: Any, missing: str = "Not specified") -> str:
        """
        Display a value without inventing a project-specific fallback.
        """
        if value is None:
            return missing

        if isinstance(value, str):
            value = value.strip()
            return value if value else missing

        return str(value)

    @staticmethod
    def _display_list(
        values: Any,
        bullet: str = "  - ",
        missing: str = "  - Not specified",
    ) -> str:
        """
        Render a list without fabricating values.
        """
        if not values:
            return missing

        if isinstance(values, str):
            values = [values]

        return "\n".join(
            f"{bullet}{str(value)}"
            for value in values
            if value is not None and str(value).strip()
        ) or missing

    @staticmethod
    def _source_reference(requirement: Dict[str, Any]) -> str:
        """
        Render source provenance truthfully.

        Does not invent SRC-001 or Page 1.
        """
        source_id = requirement.get("source_id")
        source_page = requirement.get("source_page")

        if source_id and source_page is not None:
            return f"{source_id} (Page {source_page})"

        if source_id:
            return str(source_id)

        if source_page is not None:
            return f"Page {source_page}"

        return "Not specified"

    # ------------------------------------------------------------------
    # 1. SRS
    # ------------------------------------------------------------------

    def generate_srs(
        self,
        project: Dict[str, Any],
        requirements: List[Dict[str, Any]],
    ) -> str:

        functional = [
            r for r in requirements
            if str(r.get("req_type", "")).lower() == "functional"
        ]

        non_functional = [
            r for r in requirements
            if str(r.get("req_type", "")).lower() != "functional"
        ]

        project_title = self._display(
            project.get("title"),
            "Untitled Project",
        )

        domain = self._display(
            project.get("domain"),
            "Not specified",
        )

        description = self._display(
            project.get("description"),
            "No project description was provided.",
        )

        md = f"""# Software Requirements Specification (SRS)

## Project: {project_title}

**Domain:** {domain}  
**Generated by:** ReqPilot AI Multi-Agent Engine  
**Date:** {datetime.utcnow().strftime('%Y-%m-%d %H:%M:%S UTC')}  
**Status:** Generated Report

---

### 1. Executive Summary & Scope

{description}

### 2. Functional Requirements ({len(functional)} Total)
"""

        if not functional:
            md += "\nNo functional requirements are currently persisted.\n"

        for requirement in functional:
            criteria = requirement.get("acceptance_criteria") or []

            criteria_text = self._display_list(
                criteria,
                bullet="  - ",
                missing="  - No acceptance criteria specified.",
            )

            md += f"""
#### [{self._display(requirement.get('id'), 'Unknown ID')}] {self._display(requirement.get('summary'), 'Untitled Requirement')}

- **Actor:** {self._display(requirement.get('actor'))}
- **Priority:** {self._display(requirement.get('priority'))}
- **Status:** {self._display(requirement.get('status'))}
- **Statement:** {self._display(requirement.get('description'))}
- **Preconditions:** {self._display(requirement.get('preconditions'))}
- **Expected Outcome:** {self._display(requirement.get('expected_outcome'))}
- **Acceptance Criteria:**
{criteria_text}
- **Source Grounding:** {self._source_reference(requirement)}
"""

            excerpt = requirement.get("source_excerpt")

            if excerpt:
                md += f'> *Excerpt:* "{excerpt}"\n'

        md += f"""
---

### 3. Non-Functional Requirements ({len(non_functional)} Total)
"""

        if not non_functional:
            md += "\nNo non-functional requirements are currently persisted.\n"

        for requirement in non_functional:
            quality_score = requirement.get("quality_score")

            if quality_score is not None:
                quality_text = f"{quality_score}%"
            else:
                quality_text = "Not evaluated"

            md += f"""
#### [{self._display(requirement.get('id'), 'Unknown ID')}] {self._display(requirement.get('summary'), 'Untitled Requirement')}

- **Priority:** {self._display(requirement.get('priority'))}
- **Quality Score:** {quality_text}
- **Specification:** {self._display(requirement.get('description'))}
- **Source Citation:** {self._source_reference(requirement)}
"""

        return md

    # ------------------------------------------------------------------
    # 2. QUALITY AUDIT
    # ------------------------------------------------------------------

    def generate_quality_audit(
        self,
        project: Dict[str, Any],
        requirements: List[Dict[str, Any]],
        issues: List[Dict[str, Any]],
    ) -> str:

        evaluated_scores = [
            float(r["quality_score"])
            for r in requirements
            if r.get("quality_score") is not None
        ]

        if evaluated_scores:
            average_quality = sum(evaluated_scores) / len(evaluated_scores)
            quality_text = f"{round(average_quality, 1)} / 100.0"
        else:
            quality_text = "Not evaluated"

        ambiguities = [
            i for i in issues
            if i.get("issue_type") == "ambiguity"
        ]

        conflicts = [
            i for i in issues
            if i.get("issue_type") == "conflict"
        ]

        duplicates = [
            i for i in issues
            if i.get("issue_type") == "duplicate"
        ]

        project_title = self._display(
            project.get("title"),
            "Untitled Project",
        )

        md = f"""# Requirements Quality & Risk Audit Report

## Project: {project_title}

**Overall Quality Score:** {quality_text}  
**Audit Date:** {datetime.utcnow().strftime('%Y-%m-%d')}  
**Total Requirements Evaluated:** {len(requirements)}

---

### Quality Dimension Weights & Scoring

- **Completeness (20%):** Evaluates presence of actors, actions, preconditions, and acceptance criteria.
- **Clarity (15%):** Penalizes subjective or vague terms.
- **Atomicity (15%):** Ensures single coherent behavioral statements.
- **Consistency (20%):** Validates absence of logical or temporal contradictions.
- **Testability (15%):** Checks for measurable verification conditions.
- **Feasibility (10%):** Assesses technical realism.
- **Traceability (5%):** Validates links to raw source citations.

---

### Detected Issues Summary

- **Ambiguities:** {len(ambiguities)}
- **Potential Conflicts:** {len(conflicts)}
- **Near-Duplicates / Overlaps:** {len(duplicates)}

### Active Conflict Issues
"""

        if conflicts:
            for conflict in conflicts:
                title = self._display(conflict.get("title"))
                severity = self._display(conflict.get("severity")).upper()
                description = self._display(conflict.get("description"))

                md += (
                    f"- **{title}** ({severity} Severity): "
                    f"{description}\n"
                )
        else:
            md += "\nNo active conflict issues were detected.\n"

        md += "\n### Active Ambiguity Findings\n"

        if ambiguities:
            for ambiguity in ambiguities:
                requirement_id = self._display(
                    ambiguity.get("requirement_id"),
                    "Unknown requirement",
                )

                phrase = self._display(
                    ambiguity.get("detected_phrase"),
                    "Unspecified phrase",
                )

                description = self._display(
                    ambiguity.get("description")
                )

                md += (
                    f"- **{requirement_id}:** "
                    f"Found subjective phrase *'{phrase}'*. "
                    f"{description}\n"
                )
        else:
            md += "\nNo active ambiguity findings were detected.\n"

        return md

    # ------------------------------------------------------------------
    # 3. ARCHITECTURE
    # ------------------------------------------------------------------

    def generate_architecture_report(
        self,
        project: Dict[str, Any],
        modules: List[Dict[str, Any]],
        relations: List[Dict[str, Any]],
    ) -> str:

        project_title = self._display(
            project.get("title"),
            "Untitled Project",
        )

        md = f"""# System Architecture & Technical Decomposition

## Project: {project_title}

**Total Modules:** {len(modules)}  
**Total Inter-Service Relations:** {len(relations)}

---

### Module Specifications
"""

        if not modules:
            md += "\nNo architecture modules are currently persisted.\n"

        for module in modules:
            responsibilities = self._display_list(
                module.get("responsibilities"),
                missing="  - No responsibilities specified.",
            )

            api_endpoints = self._display_list(
                [
                    f"`{endpoint}`"
                    for endpoint in (module.get("api_endpoints") or [])
                ],
                missing="  - No API endpoints specified.",
            )

            md += f"""
#### {self._display(module.get('id'), 'Unknown ID')}: {self._display(module.get('name'), 'Unnamed Module')} ({self._display(module.get('module_type'), 'module').upper()})

- **Tech Stack:** {self._display(module.get('tech_stack'))}
- **Description:** {self._display(module.get('description'))}
- **Responsibilities:**
{responsibilities}
- **Exposed APIs:**
{api_endpoints}
"""

        md += "\n---\n\n### Inter-Module Dependencies\n"

        if not relations:
            md += "\nNo inter-module dependencies are currently persisted.\n"

        for relation in relations:
            source = self._display(
                relation.get("source_module_id"),
                "Unknown source",
            )

            target = self._display(
                relation.get("target_module_id"),
                "Unknown target",
            )

            relation_type = self._display(
                relation.get("relation_type"),
                "calls",
            )

            description = self._display(
                relation.get("description")
            )

            md += (
                f"- `{source}` **--[{relation_type}]-->** "
                f"`{target}`: {description}\n"
            )

        return md

    # ------------------------------------------------------------------
    # 4. PROJECT PLAN
    # ------------------------------------------------------------------

    def generate_project_plan_report(
        self,
        project: Dict[str, Any],
        tasks: List[Dict[str, Any]],
        sprints: List[Dict[str, Any]],
    ) -> str:

        known_hours = [
            float(t["estimated_hours"])
            for t in tasks
            if t.get("estimated_hours") is not None
        ]

        known_points = [
            float(t["story_points"])
            for t in tasks
            if t.get("story_points") is not None
        ]

        total_hours = sum(known_hours)
        total_points = sum(known_points)

        hours_text = (
            f"{round(total_hours, 1)} Hours"
            if known_hours
            else "Not estimated"
        )

        points_text = (
            f"{round(total_points, 1)} Story Points"
            if known_points
            else "Not estimated"
        )

        project_title = self._display(
            project.get("title"),
            "Untitled Project",
        )

        md = f"""# Software Project Plan & Sprint Schedule

## Project: {project_title}

**Total Estimated Effort:** {hours_text} ({points_text})  
**Total Persisted Sprints:** {len(sprints)}

---

### Sprint Roadmap
"""

        if not sprints:
            md += """
No sprint schedule is currently persisted.

Tasks may exist without being assigned to a persisted sprint.
"""

        for sprint in sprints:
            sprint_name = self._display(
                sprint.get("sprint_name"),
                "Unnamed Sprint",
            )

            capacity = sprint.get("total_points")

            capacity_text = (
                f"{capacity} Points"
                if capacity is not None
                else "Not specified"
            )

            md += f"""
#### {sprint_name} (Capacity: {capacity_text})
"""

            sprint_task_ids = sprint.get("task_ids") or []

            sprint_tasks = [
                task
                for task in tasks
                if task.get("id") in sprint_task_ids
            ]

            if not sprint_tasks:
                md += "- No tasks assigned to this sprint.\n"
                continue

            for task in sprint_tasks:
                story_points = self._display(
                    task.get("story_points"),
                    "Not estimated",
                )

                estimated_hours = self._display(
                    task.get("estimated_hours"),
                    "Not estimated",
                )

                complexity = self._display(
                    task.get("complexity"),
                    "Not specified",
                )

                md += (
                    f"- **[{self._display(task.get('id'), 'Unknown ID')}]** "
                    f"{self._display(task.get('title'), 'Untitled Task')} "
                    f"({story_points} pts, {estimated_hours} hrs, "
                    f"{complexity} complexity)\n"
                )

            md += "\n"

        # Tasks without a persisted sprint are explicitly reported.
        scheduled_task_ids = {
            task_id
            for sprint in sprints
            for task_id in (sprint.get("task_ids") or [])
        }

        unscheduled_tasks = [
            task
            for task in tasks
            if task.get("id") not in scheduled_task_ids
        ]

        if unscheduled_tasks:
            md += "\n### Tasks Without Persisted Sprint Assignment\n"

            for task in unscheduled_tasks:
                md += (
                    f"- **[{self._display(task.get('id'), 'Unknown ID')}]** "
                    f"{self._display(task.get('title'), 'Untitled Task')}\n"
                )

        return md

    # ------------------------------------------------------------------
    # 5. TRACEABILITY
    # ------------------------------------------------------------------

    def generate_traceability_report(
        self,
        project: Dict[str, Any],
        matrix: List[Dict[str, Any]],
    ) -> str:

        project_title = self._display(
            project.get("title"),
            "Untitled Project",
        )

        md = f"""# End-to-End Requirements Traceability Matrix (RTM)

## Project: {project_title}

| Source Provenance | Requirement ID | Type | Architecture Module | Development Tasks | Test Cases | Traceability Status |
| :--- | :--- | :--- | :--- | :--- | :--- | :--- |
"""

        if not matrix:
            md += (
                "| Not available | None | None | None | None | None | "
                "No traceability records |\n"
            )

        for row in matrix:
            task_ids = row.get("task_ids") or []
            test_ids = row.get("test_ids") or []

            tasks_text = (
                ", ".join(task_ids)
                if task_ids
                else "None (Orphan)"
            )

            tests_text = (
                ", ".join(test_ids)
                if test_ids
                else "None (Unverified)"
            )

            module_id = row.get("module_id")
            module_text = (
                f"`{module_id}`"
                if module_id
                else "None"
            )

            source_id = row.get("source_id")
            source_page = row.get("source_page")

            if source_id and source_page is not None:
                source_text = f"{source_id}:p{source_page}"
            elif source_id:
                source_text = str(source_id)
            elif source_page is not None:
                source_text = f"p{source_page}"
            else:
                source_text = "Not specified"

            status = (
                "Linked"
                if not row.get("is_orphan")
                else "**ORPHAN**"
            )

            md += (
                f"| {source_text} | "
                f"`{self._display(row.get('requirement_id'), 'Unknown')}` | "
                f"{self._display(row.get('req_type'), 'Unknown')} | "
                f"{module_text} | "
                f"{tasks_text} | "
                f"{tests_text} | "
                f"{status} |\n"
            )

        return md

    # ------------------------------------------------------------------
    # 6. CHANGE IMPACT
    # ------------------------------------------------------------------

    def generate_change_impact_report(
        self,
        project: Dict[str, Any],
        change_requests: List[Dict[str, Any]],
    ) -> str:

        project_title = self._display(
            project.get("title"),
            "Untitled Project",
        )

        md = f"""# Requirements Change Impact & Blast Radius Audit

## Project: {project_title}

"""

        if not change_requests:
            md += "No persisted change requests are currently available.\n"
            return md

        for change_request in change_requests:
            title = self._display(
                change_request.get("title"),
                "Untitled Change Request",
            )

            requirement_id = self._display(
                change_request.get("requirement_id"),
                "Not specified",
            )

            risk = self._display(
                change_request.get("risk_level"),
                "Not assessed",
            ).upper()

            schedule = self._display(
                change_request.get("schedule_impact"),
                "Not assessed",
            )

            proposed_summary = self._display(
                change_request.get("proposed_summary")
            )

            status = self._display(
                change_request.get("status")
            )

            md += f"""### Change Request: {title}

- **Target Requirement:** `{requirement_id}`
- **Risk Severity:** {risk}
- **Schedule Impact:** {schedule}
- **Status:** {status}
- **Proposed Summary:** {proposed_summary}

#### Impacted Artifacts Blast Radius:
"""

            impact_items = change_request.get("impact_items") or []

            if not impact_items:
                md += "\nNo persisted impact artifacts are associated with this change request.\n"
                continue

            for item in impact_items:
                artifact_type = self._display(
                    item.get("artifact_type"),
                    "artifact",
                ).upper()

                artifact_id = self._display(
                    item.get("artifact_id"),
                    "Unknown",
                )

                artifact_name = self._display(
                    item.get("artifact_name"),
                    "Unnamed artifact",
                )

                severity = self._display(
                    item.get("severity"),
                    "Not assessed",
                ).upper()

                description = self._display(
                    item.get("impact_description")
                )

                md += (
                    f"- **[{artifact_type}]** `{artifact_id}` — "
                    f"{artifact_name} — **{severity}**: "
                    f"{description}\n"
                )

        return md